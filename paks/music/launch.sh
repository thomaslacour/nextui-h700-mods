#!/bin/sh
# Music — Subsonic / Navidrome player (Tools > Music).
#
# Three processes, all from this pak and Entware:
#   mpd (Entware mpd-full)   plays (FFmpeg: every format), keeps playing after exit;
#   music --serve            local relay: mpd streams http://127.0.0.1:46301,
#                            the relay adds the token and checks the home CA;
#   music                    the screens (framebuffer + evdev).
#
# Sign-in, CA and settings live in .userdata/h700/music/ (config.txt is
# written by mac/music.sh login, from the Mac). "After exit = Stop music" in
# the player's settings stops mpd and the relay when the pak closes.
# pre-launch.d/32-music-pause pauses the music before any game, so the game
# gets the audio device (mpd closes it while paused).
#
# Test entry points (no screen):
#   launch.sh --start     start mpd + relay, print their state
#   launch.sh --stop      stop both
#   launch.sh --conf      print the generated mpd.conf
PAK_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
. "$PAK_DIR/lib/paplib.sh"
paplib_init
MUSIC="$PAK_DIR/music"
MPD="${MUSIC_MPD:-/opt/bin/mpd}"
DATA="${MUSIC_DIR:-$USERDATA_PATH/music}"
SOCK="${MUSIC_MPD_SOCKET:-$TMP/music-mpd.sock}"
CONF="$DATA/mpd.conf"
ALSA_DEVICE="${MUSIC_ALSA_DEVICE:-default}"
ALSA_CONF="${MUSIC_ALSA_CONF:-/opt/share/alsa/alsa.conf:/etc/asound.conf}"
export MUSIC_DIR="$DATA" MUSIC_MPD_SOCKET="$SOCK"
mkdir -p "$DATA"
trap paplib_cleanup EXIT INT TERM HUP

write_conf() {
    cat > "$CONF.new" <<EOF
# Generated by Music.pak at each launch; edits are lost.
bind_to_address "$SOCK"
pid_file "$TMP/music-mpd.pid"
state_file "$DATA/mpd.state"
state_file_interval "20"
restore_paused "yes"
log_file "$LOGS_PATH/music-mpd.txt"
auto_update "no"
filesystem_charset "UTF-8"
input {
    plugin "curl"
}
audio_output {
    type "alsa"
    name "Console"
    device "$ALSA_DEVICE"
    format "*:16:*"
    mixer_type "none"
    buffer_time "500000"
}
audio_buffer_size "8192"
EOF
    mv -f "$CONF.new" "$CONF"
}

# Same audio path as NextUI's games and the system aplay: the "default" PCM
# of /etc/asound.conf. Its hooks keep "digital volume" (a gain, 0 = mute) at
# 63 while playing and switch the speaker on; the volume keys (keymon) then
# act on "lineout volume". Entware's ALSA reads only /opt/share/alsa, so the
# system file is added with ALSA_CONFIG_PATH. A direct hw: device is silent:
# keymon writes digital volume 0 at full volume. mpd keeps the song's own
# rate (the codec takes 8-192 kHz): no resampling.
speaker_on() {
    for ctl in SPK LINEOUT "OutputL Mixer DACL" "OutputR Mixer DACR"; do
        amixer -q -c 0 sset "$ctl" on >/dev/null 2>&1
    done
}

mpd_up() { "$MUSIC" --ctl status >/dev/null 2>&1; }
RELAY_PID="$TMP/music-relay.pid"
relay_up() { pid=$(cat "$RELAY_PID" 2>/dev/null) && [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; }

start() {
    write_conf
    if ! mpd_up; then
        rm -f "$SOCK"
        speaker_on
        # Entware's own libraries: the pak's LD_LIBRARY_PATH would mix in the
        # system ones.
        env -u LD_LIBRARY_PATH ALSA_CONFIG_PATH="$ALSA_CONF" "$MPD" "$CONF" >> "$LOGS_PATH/music-mpd.txt" 2>&1
        n=0
        while ! mpd_up && [ "$n" -lt 30 ]; do sleep 0.1; n=$((n + 1)); done
    fi
    if ! relay_up && [ -s "$DATA/config.txt" ]; then
        setsid "$MUSIC" --serve >> "$LOGS_PATH/music-relay.txt" 2>&1 < /dev/null &
        echo $! > "$RELAY_PID"
    fi
    mpd_up
}

stop() {
    "$MUSIC" --ctl stop >/dev/null 2>&1
    pid=$(cat "$TMP/music-mpd.pid" 2>/dev/null)
    [ -z "$pid" ] || kill "$pid" 2>/dev/null
    ! relay_up || kill "$pid" 2>/dev/null
    rm -f "$RELAY_PID"
}

after_exit() { sed -n 's/^after_exit *= *//p' "$DATA/settings.txt" 2>/dev/null | tail -1; }

case "${1:-}" in
--start) start; echo "mpd: $(mpd_up && echo up || echo down)"; echo "relay: $(relay_up && echo up || echo down)"; exit 0 ;;
--stop) stop; exit 0 ;;
--conf) write_conf; cat "$CONF"; exit 0 ;;
esac

paplib_log "Music"
if [ ! -x "$MPD" ]; then
    ui_message "The player (mpd) is not installed.\n\nOn the Mac:\nbash mac/install-entware.sh mpd-full" 6
    exit 1
fi
start || echo "mpd did not start (see logs/music-mpd.txt)"
"$MUSIC"
echo "player exit: $?"
if [ "$(after_exit)" = stop ]; then
    stop
    echo "stopped (after exit = stop)"
fi
