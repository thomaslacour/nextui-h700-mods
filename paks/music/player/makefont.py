#!/usr/bin/env python3
"""Build the embedded glyph atlas (font_generated.go) of the Music player.

Pillow is needed at build time only; the Go build itself uses the stdlib.
The font is read from the developer's machine, never shipped as a file: by
default the NextUI font copied from the console (mac/music.sh font), so the
player looks like the launcher's own menus.

Usage: python3 makefont.py --font PATH [--out font_generated.go]
"""
import argparse
import base64
import math
import zlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

P = argparse.ArgumentParser()
P.add_argument('--font', required=True, help='bold TTF/OTF used for every face')
P.add_argument('--out', default=str(Path(__file__).parent / 'font_generated.go'))
a = P.parse_args()

chars = [chr(i) for i in range(32, 127)]
chars += [chr(i) for i in range(0xA0, 0x180)]          # Latin-1 + Latin Extended-A
chars += list('‘’‚“”„…–—•·‹›«»€™←→↑↓★☆♪♫▶❚✓×−␣⌫⇄')
chars = list(dict.fromkeys(chars))

# name, size in px. Sizes match NextUI on a 640x480 panel.
faces = [(str(n), n) for n in (30, 24, 21, 18, 17, 15, 13, 12)]  # mock v3 sizes (px on 640x480)

font_cache = {}
def has_glyph(font, ch):
    # A glyph the font lacks renders as .notdef; compare with a known-missing one.
    try:
        missing = font.getmask('￿').getbbox()
        mask = font.getmask(ch).getbbox()
        return ch == ' ' or mask != missing or ch == '￿'
    except Exception:
        return True

def lit(ch):
    if ch == '\\':
        return "'\\\\'"
    if ch == "'":
        return "'\\''"
    if 32 <= ord(ch) < 127:
        return "'" + ch + "'"
    return "'\\u%04x'" % ord(ch)

bitmap = bytearray()
code = []
for name, size in faces:
    font = ImageFont.truetype(a.font, size)
    ascent, descent = font.getmetrics()
    h = ascent + descent + 1
    # Visual centre: cap height vs line box, so textMid looks centred.
    cap = font.getbbox('H', anchor='ls')
    shift = round(h / 2 - ((ascent + cap[1]) + ascent) / 2)
    rows = []
    for ch in chars:
        if ord(ch) >= 0x180 and not has_glyph(font, ch):
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        offx = max(0, -x0)
        adv = max(1, math.ceil(font.getlength(ch)))
        w = max(adv, x1 + offx, 1) + 1
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((offx, ascent), ch, fill=255, font=font, anchor='ls')
        rows.append('\t\t%s: {%d, %d, %d},' % (lit(ch), len(bitmap), w, adv))
        bitmap.extend(im.tobytes())
    code += ['\tface%s = rasterFont{height: %d, shift: %d, glyphs: map[rune]glyphInfo{' % (name, h, shift),
             *rows, '\t}}']

z = base64.b64encode(zlib.compress(bytes(bitmap), 9)).decode('ascii')
out = [
    '// Code generated by makefont.py; DO NOT EDIT.',
    '',
    'package main',
    '',
    'import (',
    '\t"bytes"',
    '\t"compress/zlib"',
    '\t"encoding/base64"',
    '\t"io"',
    ')',
    '',
    'type glyphInfo struct{ off, width, advance int }',
    'type rasterFont struct {',
    '\theight, shift int',
    '\tglyphs        map[rune]glyphInfo',
    '}',
    '',
    'var ' + ', '.join('face' + n for n, _ in faces) + ' rasterFont',
    'var fontAtlas []byte',
    '',
    'const fontAtlasZlib = "" +',
]
for i in range(0, len(z), 120):
    out.append('\t"%s"%s' % (z[i:i + 120], ' +' if i + 120 < len(z) else ''))
out += [
    '',
    'func init() {',
    '\tb, err := base64.StdEncoding.DecodeString(fontAtlasZlib)',
    '\tif err != nil {',
    '\t\tpanic(err)',
    '\t}',
    '\tr, err := zlib.NewReader(bytes.NewReader(b))',
    '\tif err != nil {',
    '\t\tpanic(err)',
    '\t}',
    '\tfontAtlas, err = io.ReadAll(r)',
    '\tif err != nil {',
    '\t\tpanic(err)',
    '\t}',
    *code,
    '}',
]
Path(a.out).write_text('\n'.join(out) + '\n')
print('faces', len(faces), 'atlas bytes', len(bitmap), 'source bytes', Path(a.out).stat().st_size)
