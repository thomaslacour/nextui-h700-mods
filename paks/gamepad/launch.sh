#!/bin/sh
# Gamepad — the console as a Bluetooth game pad for a Mac, PC or phone
# (Tools > Gamepad).
#
# The pak opens with Bluetooth untouched, as a key tester (it replaces
# Tools > Input). MENU + START turns the pad on: the program runs
# "launch.sh --bt-on", and "--bt-off" when it is turned off again.
#
# Bluetooth classic HID: bluetoothd's input plugin owns L2CAP PSM 17/19 (it is
# the HID *host* side), so while the pad is on bluetoothd is restarted
# with -P input and a copy of main.conf that sets the "gamepad" device class.
# The gamepad binary then registers the HID SDP record and a Just Works agent
# over D-Bus, listens on PSM 17/19 and sends the console buttons. On exit the
# stock bluetoothd and bluealsa are started again with their own command
# lines (the console's Bluetooth pads and audio come back).
#
# Entry points used by the program (exit 2 = Bluetooth is off in Settings):
#   launch.sh --bt-on     stock bluetoothd -> bluetoothd for the pad
#   launch.sh --bt-off    back to the stock bluetoothd and bluealsa
#
# Test entry points (no screen):
#   launch.sh --check     restart bluetoothd for the pak, run gamepad --check, restore
#   launch.sh --conf      print the generated main.conf
PAK_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
. "$PAK_DIR/lib/paplib.sh"
paplib_init
PAD="$PAK_DIR/gamepad"
BTD="${GAMEPAD_BLUETOOTHD:-/usr/libexec/bluetooth/bluetoothd}"
STOCK_CONF="${GAMEPAD_STOCK_CONF:-/etc/bluetooth/main.conf}"
CONF="$TMP/gamepad-main.conf"
SAVED="$TMP/gamepad-saved"
export GAMEPAD_DIR="$USERDATA_PATH/gamepad"
mkdir -p "$GAMEPAD_DIR"

cmdline() { tr '\0' ' ' < "/proc/$1/cmdline" 2>/dev/null; }

# Class 0x000508 = peripheral / gamepad (bluetoothd adds the service bits).
# DeviceID = the Xbox One S controller over Bluetooth (USB vendor source,
# 045E:02E0, Windows report format): hosts pick their Xbox driver / mapping
# from it (see pad/hid.go).
write_conf() {
    {
        echo "# Generated by Gamepad.pak; the stock file is untouched."
        if [ -r "$STOCK_CONF" ]; then
            awk '
                /^[ \t]*\[/ { sec = $0; gsub(/[ \t\[\]]/, "", sec) }
                sec == "General" && /^[ \t]*(Class|DeviceID|DiscoverableTimeout|PairableTimeout|JustWorksRepairing)[ \t]*=/ { next }
                { print }
                /^[ \t]*\[General\]/ { done = 1; print "Class = 0x000508"; print "DeviceID = usb:045E:02E0:0903"; print "DiscoverableTimeout = 0";
                    print "PairableTimeout = 0"; print "JustWorksRepairing = always" }
                END { if (!done) { print "[General]"; print "Class = 0x000508"; print "DeviceID = usb:045E:02E0:0903"; print "DiscoverableTimeout = 0";
                    print "PairableTimeout = 0"; print "JustWorksRepairing = always" } }
            ' "$STOCK_CONF"
        else
            printf '[General]\nClass = 0x000508\nDeviceID = usb:045E:02E0:0903\nDiscoverableTimeout = 0\nPairableTimeout = 0\nJustWorksRepairing = always\n'
        fi
    } > "$CONF"
}

wait_gone() { n=0; while kill -0 "$1" 2>/dev/null && [ "$n" -lt 30 ]; do sleep 0.1; n=$((n + 1)); done; kill -9 "$1" 2>/dev/null; }

# bt_for_pad: stock bluetoothd -> bluetoothd -P input with our main.conf.
bt_for_pad() {
    pid=$(pidof bluetoothd | awk '{print $1}')
    [ -n "$pid" ] || return 1
    case "$(cmdline "$pid")" in *gamepad-main.conf*) return 0 ;; esac # already ours (earlier crash)
    alsa=$(pidof bluealsa | awk '{print $1}')
    { echo "BTD_CMD=$(cmdline "$pid")"; echo "ALSA_CMD=$( [ -z "$alsa" ] || cmdline "$alsa")"; } > "$SAVED"
    write_conf
    kill "$pid"
    wait_gone "$pid"
    setsid "$BTD" -n -P input -f "$CONF" >> "$LOGS_PATH/gamepad-bluetoothd.txt" 2>&1 < /dev/null &
    n=0
    while [ "$n" -lt 50 ]; do
        timeout 2 bluetoothctl show 2>/dev/null | grep -q 'Powered:' && return 0
        sleep 0.1
        n=$((n + 1))
    done
    echo "bluetoothd for the pad did not answer"
    return 1
}

# bt_restore: our bluetoothd -> stock bluetoothd and bluealsa (same command lines).
bt_restore() {
    [ -s "$SAVED" ] || return 0
    BTD_CMD=$(sed -n 's/^BTD_CMD=//p' "$SAVED")
    ALSA_CMD=$(sed -n 's/^ALSA_CMD=//p' "$SAVED")
    for pid in $(pidof bluetoothd); do
        case "$(cmdline "$pid")" in *gamepad-main.conf*) kill "$pid"; wait_gone "$pid" ;; esac
    done
    pidof bluetoothd >/dev/null || setsid ${BTD_CMD:-$BTD} >/dev/null 2>&1 < /dev/null &
    if [ -n "$ALSA_CMD" ]; then
        for pid in $(pidof bluealsa); do kill "$pid"; wait_gone "$pid"; done
        sleep 1 # bluealsa registers its endpoints with the new bluetoothd
        setsid $ALSA_CMD >/dev/null 2>&1 < /dev/null &
    fi
    rm -f "$SAVED"
    echo "bluetooth restored: $BTD_CMD${ALSA_CMD:+ + $ALSA_CMD}"
}

cleanup() { bt_restore; paplib_cleanup; }

case "${1:-}" in
--conf) write_conf; cat "$CONF"; exit 0 ;;
--bt-on)
    if [ ! -d /sys/class/bluetooth/hci0 ] || ! pidof bluetoothd >/dev/null; then
        echo "bluetooth is off"
        exit 2
    fi
    bt_for_pad
    exit
    ;;
--bt-off) bt_restore; exit 0 ;;
--check)
    trap cleanup EXIT INT TERM HUP
    bt_for_pad || exit 1
    "$PAD" --check
    exit 0
    ;;
esac

paplib_log "Gamepad"
export GAMEPAD_LAUNCH="$PAK_DIR/launch.sh"
trap cleanup EXIT INT TERM HUP
"$PAD"
echo "gamepad exit: $?"
