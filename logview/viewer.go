type framebuffer struct {
	fd                         int
	mapped                     []byte
	w, h                       int
	stride                     int
	virtH                      int
	bpp                        int
	chanR, chanG, chanB, chanA channel
}
type channel struct{ off, length uint32 }

func le32(b []byte, n int) uint32 { return binary.LittleEndian.Uint32(b[n : n+4]) }
func le16(b []byte, n int) uint16 { return binary.LittleEndian.Uint16(b[n : n+2]) }

func openFramebuffer() (*framebuffer, error) {
	fd, err := syscall.Open("/dev/fb0", syscall.O_RDWR|syscall.O_CLOEXEC, 0)
	if err != nil {
		return nil, fmt.Errorf("open /dev/fb0: %w", err)
	}
	bad := func(e error) (*framebuffer, error) { syscall.Close(fd); return nil, e }
	var v [256]byte
	_, _, e := syscall.Syscall(syscall.SYS_IOCTL, uintptr(fd), fbGetVar, uintptr(unsafe.Pointer(&v[0])))
	if e != 0 {
		return bad(fmt.Errorf("FBIOGET_VSCREENINFO: %w", e))
	}
	var f [128]byte
	_, _, e = syscall.Syscall(syscall.SYS_IOCTL, uintptr(fd), fbGetFix, uintptr(unsafe.Pointer(&f[0])))
	if e != 0 {
		return bad(fmt.Errorf("FBIOGET_FSCREENINFO: %w", e))
	}
	fb := &framebuffer{fd: fd, w: int(le32(v[:], 0)), h: int(le32(v[:], 4)), virtH: int(le32(v[:], 12)), bpp: int(le32(v[:], 24)), stride: int(le32(f[:], 48)),
		chanR: channel{le32(v[:], 32), le32(v[:], 36)},
		chanG: channel{le32(v[:], 44), le32(v[:], 48)},
		chanB: channel{le32(v[:], 56), le32(v[:], 60)},
		chanA: channel{le32(v[:], 68), le32(v[:], 72)},
	}
	if fb.w < 320 || fb.w > 2048 || fb.h < 200 || fb.h > 2048 || fb.bpp != 16 && fb.bpp != 24 && fb.bpp != 32 {
		return bad(fmt.Errorf("unexpected framebuffer %dx%d %dbpp", fb.w, fb.h, fb.bpp))
	}
	if fb.virtH < fb.h {
		fb.virtH = fb.h
	}
	size := fb.stride * fb.virtH
	if smem := int(le32(f[:], 24)); smem > 0 && smem < size {
		size = smem
	}
	if size <= 0 || size > 64*1024*1024 {
		return bad(errors.New("taille unexpected framebuffere"))
	}
	buf, err := syscall.Mmap(fd, 0, size, syscall.PROT_READ|syscall.PROT_WRITE, syscall.MAP_SHARED)
	if err != nil {
		return bad(fmt.Errorf("mmap: %w", err))
	}
	fb.mapped = buf
	return fb, nil
}
func (f *framebuffer) close() { syscall.Munmap(f.mapped); syscall.Close(f.fd) }
func (f *framebuffer) pack(r, g, b uint8) uint32 {
	pack := func(c uint8, p channel) uint32 {
		if p.length == 0 || p.length > 8 || p.off > 31 {
			return 0
		}
		return ((uint32(c)*((1<<p.length)-1) + 127) / 255) << p.off
	}
	v := pack(r, f.chanR) | pack(g, f.chanG) | pack(b, f.chanB)
	if f.chanA.length > 0 && f.chanA.length <= 8 && f.chanA.off < 32 {
		v |= ((1 << f.chanA.length) - 1) << f.chanA.off
	}
	return v
}
func (f *framebuffer) drawPixels(img []uint32) {
	if len(img) < f.w*f.h {
		return
	}
	// Update all framebuffer pages so active scanout gets the same image, whatever yoffset.
	pages := f.virtH / f.h
	if pages < 1 {
		pages = 1
	}
	if pages > 4 {
		pages = 4
	}
	pixelBytes := f.bpp / 8
	for page := 0; page < pages; page++ {
		for y := 0; y < f.h; y++ {
			dst := (page*f.h + y) * f.stride
			for x := 0; x < f.w; x++ {
				p := img[y*f.w+x]
				off := dst + x*pixelBytes
				if off+pixelBytes > len(f.mapped) {
					continue
				}
				for k := 0; k < pixelBytes; k++ {
					f.mapped[off+k] = byte(p >> (k * 8))
				}
			}
		}
	}
}

type canvas struct {
	w, h   int
	pixels []uint32
	fb     *framebuffer
}

func newCanvas(f *framebuffer) *canvas {
	return &canvas{w: f.w, h: f.h, pixels: make([]uint32, f.w*f.h), fb: f}
}
func (c *canvas) rect(x, y, w, h int, col uint32) {
	if x < 0 {
		w += x
		x = 0
	}
	if y < 0 {
		h += y
		y = 0
	}
	if x+w > c.w {
		w = c.w - x
	}
	if y+h > c.h {
		h = c.h - y
	}
	if w <= 0 || h <= 0 {
		return
	}
	for yy := y; yy < y+h; yy++ {
		row := c.pixels[yy*c.w+x : yy*c.w+x+w]
		for i := range row {
			row[i] = col
		}
	}
}

// Render a proportional, antialiased raster font directly into the native FB.
// Glyph coordinates are 1:1 in native display pixels (640x480 on RG35XX SP).
// A/B/Menu navigation is handled separately; no SDL theme resources are overwritten.
func fontWidth(face *rasterFont, s string) int {
	w := 0
	for _, ch := range s {
		g, ok := face.glyphs[ch]
		if !ok {
			g = face.glyphs['?']
		}
		w += g.advance
	}
	return w
}
func pixelTruncate(face *rasterFont, s string, maxWidth int) string {
	if maxWidth <= 0 {
		return ""
	}
	if fontWidth(face, s) <= maxWidth {
		return s
	}
	ending := "..."
	limit := maxWidth - fontWidth(face, ending)
	if limit < 0 {
		return ""
	}
	width := 0
	var buf []rune
	for _, r := range s {
		g, ok := face.glyphs[r]
		if !ok {
			g = face.glyphs['?']
		}
		if width+g.advance > limit {
			break
		}
		width += g.advance
		buf = append(buf, r)
	}
	return string(buf) + ending
}
func (c *canvas) blendPacked(dst, src uint32, a uint8) uint32 {
	if a == 255 {
		return src
	}
	if a == 0 {
		return dst
	}
	result := dst
	for _, ch := range []channel{c.fb.chanR, c.fb.chanG, c.fb.chanB} {
		if ch.length == 0 || ch.length > 8 || ch.off > 31 {
			continue
		}
		mask := uint32((1 << ch.length) - 1)
		oldv := (dst >> ch.off) & mask
		newv := (src >> ch.off) & mask
		mix := (oldv*uint32(255-a) + newv*uint32(a) + 127) / 255
		result = (result & ^(mask << ch.off)) | ((mix & mask) << ch.off)
	}
	return result
}
func (c *canvas) textFace(x, y int, face *rasterFont, s string, col uint32) {
	for _, ch := range s {
		g, ok := face.glyphs[ch]
		if !ok {
			g = face.glyphs['?']
		}
		if x+g.advance > c.w-4 {
			return
		}
		if x+g.width > 0 {
			for gy := 0; gy < face.height; gy++ {
				yy := y + gy
				if yy < 0 || yy >= c.h {
					continue
				}
				src := g.off + gy*g.width
				for gx := 0; gx < g.width; gx++ {
					xx := x + gx
					if xx < 0 || xx >= c.w {
						continue
					}
					alpha := fontAtlas[src+gx]
					if alpha == 0 {
						continue
					}
					idx := yy*c.w + xx
					c.pixels[idx] = c.blendPacked(c.pixels[idx], col, alpha)
				}
			}
		}
		x += g.advance
	}
}
func (c *canvas) pill(x, y, w, h, r int, col uint32) {
	if w <= 0 || h <= 0 {
		return
	}
	if r > h/2 {
		r = h / 2
	}
	if r > w/2 {
		r = w / 2
	}
	for dy := 0; dy < h; dy++ {
		inset := 0
		if dy < r || dy >= h-r {
			edge := dy
			if dy >= h-r {
				edge = h - 1 - dy
			}
			yy := r - edge
			// integer approximation sufficient for the small MinUI-style corners
			for inset < r && (inset-r)*(inset-r)+yy*yy > r*r {
				inset++
			}
		}
		c.rect(x+inset, y+dy, w-2*inset, 1, col)
	}
}

func (c *canvas) finish() { c.fb.drawPixels(c.pixels) }

// Mise en page : une ligne d'en-tête discrète, puis le texte jusqu'en bas.
// Aucun rappel de bouton : la lecture occupe tout l'écran.
const (
	sideMargin   = 24 // marge gauche/droite
	headerTop    = 6  // haut du titre et du compteur
	ruleY        = 34 // filet de séparation sous l'en-tête
	bodyTop      = 42 // haut de la première ligne de texte
	bodyLeading  = 19 // interligne du texte
	bottomMargin = 10 // marge sous la dernière ligne
)

// ui : tout l'état de l'écran — le texte chargé et la ligne du haut affichée.
// `title` est le titre discret affiché en haut à gauche.
type ui struct {
	fb     *framebuffer
	cvs    *canvas
	title  string
	offset int
	lines  []string
	keyCh  chan keyEvent
}

func loadLines(path string, maxChars int) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		return nil, err
	}
	prefix := ""
	if st.Size() > maxFileBytes {
		_, err = f.Seek(-maxFileBytes, io.SeekEnd)
		if err != nil {
			return nil, err
		}
		br := bufio.NewReader(f)
		br.ReadString('\n')
		prefix = "[Truncated: showing last 650 KiB]"
		fReader := io.Reader(br)
		return readWrap(fReader, maxChars, prefix), nil
	}
	return readWrap(f, maxChars, prefix), nil
}
func readWrap(r io.Reader, maxChars int, prefix string) []string {
	lines := make([]string, 0, 256)
	if prefix != "" {
		lines = append(lines, prefix)
	}
	scanner := bufio.NewScanner(r)
	scanner.Buffer(make([]byte, 8192), 512*1024)
	for scanner.Scan() {
		raw := strings.ReplaceAll(strings.ReplaceAll(scanner.Text(), "\t", "    "), "\r", "")
		for len(raw) > 0 {
			rr := []rune(raw)
			if len(rr) <= maxChars {
				lines = append(lines, raw)
				break
			}
			lines = append(lines, string(rr[:maxChars]))
			raw = string(rr[maxChars:])
			if len(lines) > 12000 {
				break
			}
		}
		if len(raw) == 0 {
			lines = append(lines, "")
		}
		if len(lines) > 12000 {
			break
		}
	}
	if err := scanner.Err(); err != nil {
		lines = append(lines, "[Read error: "+err.Error()+"]")
	}
	if len(lines) == 0 {
		lines = []string{"(empty file)"}
	}
	return lines
}
func (u *ui) cols() int {
	// The logs use a monospaced 13px font, not the 24px menu font.
	charWidth := fontWidth(&faceBody, "M")
	if charWidth <= 0 {
		charWidth = 8
	}
	n := (u.fb.w - 2*sideMargin) / charWidth
	if n < 20 {
		return 20
	}
	return n
}

// rows : nombre de lignes de texte affichables, en-tête déduit.
func (u *ui) rows() int {
	n := (u.fb.h - bodyTop - bottomMargin) / bodyLeading
	if n < 5 {
		return 5
	}
	return n
}

// open charge le fichier à lire. Un fichier illisible n'est pas fatal : le
// message d'erreur devient le texte affiché, l'utilisateur sort avec B.
func (u *ui) open(path string) {
	lines, err := loadLines(path, u.cols())
	if err != nil {
		u.lines = []string{"Cannot read file:", path, err.Error()}
	} else {
		u.lines = lines
	}
	u.offset = 0
}
func (u *ui) draw() {
	c := u.cvs
	black := u.fb.pack(0, 0, 0)
	white := u.fb.pack(247, 250, 247)
	muted := u.fb.pack(128, 131, 128)
	rule := u.fb.pack(38, 40, 38)
	warn := u.fb.pack(248, 191, 104)
	c.rect(0, 0, c.w, c.h, black)

	visible := u.rows()
	if u.offset > len(u.lines)-visible {
		u.offset = len(u.lines) - visible
	}
	if u.offset < 0 {
		u.offset = 0
	}

	// En-tête discret : titre à gauche, position à droite, filet fin dessous.
	// Le compteur n'apparaît que si le texte dépasse un écran.
	counter := ""
	if len(u.lines) > visible {
		counter = fmt.Sprintf("%d-%d / %d", u.offset+1, min(u.offset+visible, len(u.lines)), len(u.lines))
	}
	counterWidth := fontWidth(&faceHint, counter)
	if u.title != "" {
		maxTitle := c.w - 2*sideMargin - counterWidth - 16
		c.textFace(sideMargin, headerTop, &faceHint,
			pixelTruncate(&faceHint, u.title, maxTitle), white)
	}
	if counter != "" {
		c.textFace(c.w-sideMargin-counterWidth, headerTop, &faceHint, counter, muted)
	}
	c.rect(sideMargin, ruleY, c.w-2*sideMargin, 1, rule)

	for i := 0; i < visible && u.offset+i < len(u.lines); i++ {
		line := u.lines[u.offset+i]
		col := white
		lower := strings.ToLower(line)
		if strings.Contains(lower, "erreur") || strings.Contains(lower, "error") || strings.Contains(line, "WARNING") {
			col = warn
		}
		c.textFace(sideMargin, bodyTop+i*bodyLeading, &faceBody,
			pixelTruncate(&faceBody, line, c.w-2*sideMargin), col)
	}
	c.finish()
}

var reEvent = regexp.MustCompile(`event[0-9]+`)

// These are Linux evdev codes, not SDL button indices. NextUI rc11 maps its
// H700 SDL gamepad differently, but the evdev MENU is KEY_GOTO (354).
type keyEvent struct {
	action  string
	pressed bool
	code    uint16
}

func translateEvdev(typ, code uint16, value int32) (keyEvent, bool) {
	if typ == 1 { // EV_KEY
		if value != 0 && value != 1 && value != 2 {
			return keyEvent{}, false
		}
		action := ""
		switch code {
		case 103, 544:
			action = "up"
		case 108, 545:
			action = "down"
		case 105, 546:
			action = "left"
		case 106, 547:
			action = "right"
		case 304, 28:
			action = "open" // BTN_SOUTH: physical A on this H700 NextUI layout
		case 305:
			action = "back" // BTN_EAST: physical B on this H700 NextUI layout
		case 315:
			action = "start"
		case 314:
			action = "select"
		case 354, 139:
			action = "menu" // KEY_GOTO on H700, KEY_MENU fallback
		case 310:
			action = "pageup"
		case 311:
			action = "pagedown"
		}
		if action == "" {
			return keyEvent{}, false
		}
		// The repeat scheduler handles held directions for both key and HAT
		// devices. Ignore kernel-generated repeat to avoid double scrolling.
		if value == 2 {
			return keyEvent{}, false
		}
		return keyEvent{action: action, pressed: value != 0, code: code}, true
	}
	if typ == 3 { // EV_ABS, D-pad ABS_HAT0X/Y
		switch code {
		case 17:
			if value < 0 {
				return keyEvent{action: "up", pressed: true}, true
			}
			if value > 0 {
				return keyEvent{action: "down", pressed: true}, true
			}
		case 16:
			if value < 0 {
				return keyEvent{action: "left", pressed: true}, true
			}
			if value > 0 {
				return keyEvent{action: "right", pressed: true}, true
			}
		}
	}
	return keyEvent{}, false
}

// HAT axes emit value 0 when released. Translate that into a release for
// the previous direction; without it, software repeat would never stop.
func hatEvents(code uint16, value int32, previous string) (string, []keyEvent) {
	if code != 16 && code != 17 {
		return previous, nil
	}
	next := ""
	if value != 0 {
		if ev, ok := translateEvdev(3, code, value); ok {
			next = ev.action
		}
	}
	if next == previous {
		return next, nil
	}
	events := []keyEvent{}
	if previous != "" {
		events = append(events, keyEvent{action: previous, pressed: false, code: code})
	}
	if next != "" {
		events = append(events, keyEvent{action: next, pressed: true, code: code})
	}
	return next, events
}

func isRepeatable(action string) bool {
	switch action {
	case "up", "down", "left", "right", "pageup", "pagedown":
		return true
	}
	return false
}

const (
	repeatDelay      = 310 * time.Millisecond
	repeatPeriod     = 88 * time.Millisecond
	repeatFastAfter  = 1600 * time.Millisecond
	repeatFastPeriod = 52 * time.Millisecond
)

type repeatState struct {
	started, next time.Time
}
type keyRepeater struct {
	active map[string]repeatState
}

func newKeyRepeater() *keyRepeater {
	return &keyRepeater{active: map[string]repeatState{}}
}
func (r *keyRepeater) update(ev keyEvent, now time.Time) {
	if !isRepeatable(ev.action) {
		return
	}
	if !ev.pressed {
		delete(r.active, ev.action)
		return
	}
	if _, exists := r.active[ev.action]; !exists {
		r.active[ev.action] = repeatState{started: now, next: now.Add(repeatDelay)}
	}
}
func (r *keyRepeater) due(now time.Time) []string {
	actions := make([]string, 0, len(r.active))
	// Deterministic order is helpful when two directions are pressed together.
	for _, action := range []string{"up", "down", "left", "right", "pageup", "pagedown"} {
		st, exists := r.active[action]
		if !exists || now.Before(st.next) {
			continue
		}
		actions = append(actions, action)
		period := repeatPeriod
		if now.Sub(st.started) >= repeatFastAfter {
			period = repeatFastPeriod
		}
		st.next = now.Add(period)
		r.active[action] = st
	}
	return actions
}

func inputPaths() []string {
	data, _ := os.ReadFile("/proc/bus/input/devices")
	blocks := strings.Split(string(data), "\n\n")
	primary, secondary := []string{}, []string{}
	for _, block := range blocks {
		lower := strings.ToLower(block)
		matches := reEvent.FindAllString(block, -1)
		if strings.Contains(lower, "anbernic-keys") {
			for _, ev := range matches {
				primary = append(primary, "/dev/input/"+ev)
			}
		}
		if strings.Contains(lower, "gamepad") || strings.Contains(lower, "joystick") || strings.Contains(lower, "gpio-keys") {
			for _, ev := range matches {
				secondary = append(secondary, "/dev/input/"+ev)
			}
		}
	}
	found := primary
	if len(found) == 0 {
		found = secondary
	}
	if len(found) == 0 {
		found, _ = filepath.Glob("/dev/input/event*")
	}
	unique := map[string]bool{}
	out := []string{}
	for _, p := range found {
		if !unique[p] {
			unique[p] = true
			out = append(out, p)
		}
	}
	return out
}
func listenInput(ch chan keyEvent) error {
	paths := inputPaths()
	if len(paths) == 0 {
		return errors.New("no /dev/input/event* input")
	}
	opened := 0
	for _, path := range paths {
		fd, err := syscall.Open(path, syscall.O_RDONLY|syscall.O_NONBLOCK|syscall.O_CLOEXEC, 0)
		if err != nil {
			continue
		}
		opened++
		go func(fd int) {
			defer syscall.Close(fd)
			var b [24]byte
			var pending []byte
			hats := map[uint16]string{}
			for {
				n, err := syscall.Read(fd, b[:])
				if err == syscall.EAGAIN || err == syscall.EINTR {
					time.Sleep(15 * time.Millisecond)
					continue
				}
				if err != nil {
					return
				}
				if n == 0 {
					time.Sleep(15 * time.Millisecond)
					continue
				}
				pending = append(pending, b[:n]...)
				for len(pending) >= 24 {
					e := pending[:24]
					pending = pending[24:]
					typ, code, value := le16(e, 16), le16(e, 18), int32(le32(e, 20))
					events := []keyEvent{}
					if typ == 3 && (code == 16 || code == 17) {
						var updates []keyEvent
						hats[code], updates = hatEvents(code, value, hats[code])
						events = append(events, updates...)
					} else if ev, ok := translateEvdev(typ, code, value); ok {
						events = append(events, ev)
					}
					for _, ev := range events {
						select {
						case ch <- ev:
						default:
						}
					}
				}
			}
		}(fd)
	}
	if opened == 0 {
		return errors.New("no controller input available")
	}
	return nil
}
func (u *ui) apply(ev keyEvent, held map[string]bool) bool {
	if ev.action == "" {
		return false
	}
	if ev.action == "start" || ev.action == "select" {
		held[ev.action] = ev.pressed
	}
	if !ev.pressed {
		return false
	}
	// MENU quits immediately, including during text reading.
	if ev.action == "menu" {
		return true
	}
	// Secondary exit shortcut, useful if a device doesn't emit KEY_GOTO.
	if held["select"] && held["start"] {
		return true
	}
	// START by itself is intentionally unbound: never scroll or change page.
	if ev.action == "start" || ev.action == "select" {
		return false
	}
	rows := u.rows()
	switch ev.action {
	case "back":
		// Lecture d'un fichier : B rend la main au menu du pak.
		return true
	case "up":
		if u.offset > 0 {
			u.offset--
		}
	case "down":
		if u.offset+rows < len(u.lines) {
			u.offset++
		}
	case "left", "pageup":
		u.offset -= rows
		if u.offset < 0 {
			u.offset = 0
		}
	case "right", "pagedown":
		u.offset += rows
		if u.offset+rows > len(u.lines) {
			u.offset = len(u.lines) - rows
		}
		if u.offset < 0 {
			u.offset = 0
		}
	}
	return false
}

// run : boucle d'entrée + rafraîchissement. Le fichier à lire est déjà
// chargé par newUI.
func (u *ui) run() error {
	u.keyCh = make(chan keyEvent, 64)
	if err := listenInput(u.keyCh); err != nil {
		return err
	}
	u.draw()
	held := map[string]bool{}
	repeater := newKeyRepeater()
	ticker := time.NewTicker(20 * time.Millisecond)
	defer ticker.Stop()
	for {
		select {
		case ev, ok := <-u.keyCh:
			if !ok {
				return nil
			}
			repeater.update(ev, time.Now())
			if u.apply(ev, held) {
				return nil
			}
			if ev.pressed {
				u.draw()
			}
		case now := <-ticker.C:
			for _, action := range repeater.due(now) {
				if u.apply(keyEvent{action: action, pressed: true}, held) {
					return nil
				}
				u.draw()
			}
		}
	}
}

// options : arguments de la ligne de commande.
type options struct {
	file    string
	title   string
	preview string
}

const usageText = `log-viewer — full-screen text reader (RG35XX SP)

  --file <path>      file to read
  --title <title>    small title shown top left
  --preview <png>    render 640x480 off-device (tests), then exit

Buttons: B or MENU = quit, UP/DOWN = line, LEFT/RIGHT = page.
`

func parseArgs(args []string) (options, error) {
	var o options
	for i := 0; i < len(args); i++ {
		next := func() (string, error) {
			if i+1 >= len(args) {
				return "", fmt.Errorf("option %s: missing value", args[i])
			}
			i++
			return args[i], nil
		}
		var err error
		switch args[i] {
		case "--file":
			o.file, err = next()
		case "--title":
			o.title, err = next()
		case "--preview":
			o.preview, err = next()
		case "-h", "--help":
			return o, errUsage
		default:
			return o, fmt.Errorf("unknown option: %s", args[i])
		}
		if err != nil {
			return o, err
		}
	}
	if o.file == "" && o.preview != "" {
		o.file = os.DevNull
	}
	return o, nil
}

var errUsage = errors.New("usage")

// newUI prépare l'écran : le fichier demandé, prêt à défiler.
func newUI(fb *framebuffer, o options) *ui {
	title := o.title
	if title == "" && o.file != "" && o.file != os.DevNull {
		title = filepath.Base(o.file)
	}
	u := &ui{fb: fb, cvs: newCanvas(fb), title: title}
	u.open(o.file)
	return u
}

// renderPreview dessine l'écran dans une image 640x480 sans framebuffer :
// c'est le point d'entrée des tests hors console.
func renderPreview(o options) error {
	w, h := 640, 480
	fb := &framebuffer{w: w, h: h, virtH: h, stride: w * 4, bpp: 32,
		chanR: channel{16, 8}, chanG: channel{8, 8}, chanB: channel{0, 8}, chanA: channel{24, 8},
		mapped: make([]byte, w*h*4)}
	u := newUI(fb, o)
	u.draw()
	rgba := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			p := u.cvs.pixels[y*w+x]
			rgba.SetRGBA(x, y, color.RGBA{uint8(p >> 16), uint8(p >> 8), uint8(p), 255})
		}
	}
	f, err := os.Create(o.preview)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, rgba)
}

func main() {
	o, err := parseArgs(os.Args[1:])
	if err == errUsage {
		fmt.Fprint(os.Stderr, usageText)
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "log-viewer:", err)
		fmt.Fprint(os.Stderr, usageText)
		os.Exit(2)
	}
	if o.preview != "" {
		if err := renderPreview(o); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if o.file == "" {
		fmt.Fprint(os.Stderr, usageText)
		os.Exit(2)
	}
	fb, err := openFramebuffer()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer fb.close()
	u := newUI(fb, o)
	if err := u.run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
