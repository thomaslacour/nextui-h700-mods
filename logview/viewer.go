// log-viewer — lecteur de journaux plein écran pour la RG35XX SP (H700).
//
// Linux ARM64, Go stdlib uniquement, écrit directement dans /dev/fb0 et lit les
// boutons en evdev : aucune bibliothèque SDL, aucun fichier du système touché.
// Il descend du lecteur de l'ancien pak Diagnostics (même police embarquée,
// voir makefont.py) et sert aux deux paks (paks/lib/paplib.sh : ui_read).
//
// Rôle : afficher du TEXTE, en petit mono (DejaVu Sans Mono 13, embarquée dans
// font_generated.go), avec défilement libre — c'est le « terminal de lecture »
// commun aux paks (journaux, rapports, sections). Il ne modifie rien :
//
//	log-viewer --file <chemin> --title <titre>    lire un fichier
//	log-viewer --preview <png>                    rendu hors console (test)
//
// Volontairement minimal : pas de menu, pas de rappels de boutons en bas, juste
// une ligne d'en-tête discrète (titre à gauche, position à droite) puis le
// texte. Les menus, eux, restent des listes natives minui-list côté lanceur.
//
// Boutons : B ou MENU = quitter, HAUT/BAS = ligne à ligne,
// GAUCHE/DROITE = page par page (répétition automatique).
